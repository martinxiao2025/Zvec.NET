# sync-agents.ps1 — 智能体映射同步（幂等）
# 源: .agents/agents/*.md（规范源，入库）
# 目标1: .zcode/agents/*.md —— ZCode 副本（原样复制，入库，随 git 分发；.gitignore 已放行该子目录）
# 目标2: .github/agents/*.agent.md —— Copilot 映射（格式转换，入库；Chat 中 @<name> 唤起）
# 用法: powershell -File .agents/skills/task-pipeline/scripts/sync-agents.ps1 [-SkipZcode] [-SkipCopilot]
param(
    [switch]$SkipZcode,
    [switch]$SkipCopilot
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path
$srcDir = Join-Path $root '.agents\agents'
$copilotDir = Join-Path $root '.github\agents'
$zcodeDir = Join-Path $root '.zcode\agents'

if (-not (Test-Path $srcDir)) { Write-Error "未找到规范源目录 $srcDir"; exit 1 }

# Copilot 工具名映射（如官方规范演进，改这里）
$toolMap = @{
    'task-executor' = 'read, edit, search, run, think, ask'
    'task-reviewer' = 'read, search, run, think, ask'
}

# --- 1) ZCode 副本（规范源即 ZCode 格式，原样复制；内容相同则跳过）---
if (-not $SkipZcode) {
    New-Item -ItemType Directory -Force -Path $zcodeDir | Out-Null
    foreach ($file in Get-ChildItem $srcDir -Filter '*.md') {
        $target = Join-Path $zcodeDir $file.Name
        $changed = -not (Test-Path $target) -or ([System.IO.File]::ReadAllText($target) -ne [System.IO.File]::ReadAllText($file.FullName))
        if ($changed) {
            Copy-Item -Force $file.FullName $target
            Write-Host "[OK] 已复制 $target"
        } else {
            Write-Host "[=] 无变化 $target"
        }
    }
}

# --- 2) Copilot .agent.md 生成 ---
if (-not $SkipCopilot) {
    New-Item -ItemType Directory -Force -Path $copilotDir | Out-Null
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    foreach ($file in Get-ChildItem $srcDir -Filter '*.md') {
        $content = [System.IO.File]::ReadAllText($file.FullName)
        if ($content -notmatch '(?s)^---\s*\r?\n(.*?)\r?\n---\s*\r?\n(.*)$') {
            Write-Warning "[跳过] $($file.Name) 缺少 frontmatter"; continue
        }
        $front = $Matches[1]; $body = $Matches[2]
        $name = if ($front -match '(?m)^name:\s*(.+)$') { $Matches[1].Trim() } else { $file.BaseName }
        $desc = if ($front -match '(?m)^description:\s*(.+)$') { $Matches[1].Trim() } else { '' }
        $desc = $desc.Trim('"').Trim("'")
        $tools = if ($toolMap.ContainsKey($name)) { $toolMap[$name] } else { 'read, search' }
        $out = @"
---
name: $name
description: $desc
tools: [$tools]
---
<!-- AUTO-GENERATED by sync-agents.ps1 — 请编辑 .agents/agents/$($file.Name)，然后重跑本脚本 -->
$body
"@
        $target = Join-Path $copilotDir "$name.agent.md"
        $changed = -not (Test-Path $target) -or ([System.IO.File]::ReadAllText($target) -ne $out)
        [System.IO.File]::WriteAllText($target, $out, $utf8)
        if ($changed) { Write-Host "[OK] 已生成 $target" } else { Write-Host "[=] 无变化 $target" }
    }
}
Write-Host '同步完成。'
