# sync-agents.ps1 — 智能体映射同步（config 驱动，幂等）
# 源: .agents/agents/<name>/{agent.md, config.json}（规范源，入库；frontmatter 取 name/description，tools/model 取 config.json）
# 目标1: .zcode/agents/<name>.md —— ZCode 副本（入库，随 git 分发；.gitignore 已放行该子目录）
# 目标2: .github/agents/<name>.agent.md —— Copilot 映射（入库；Chat 中 @<name> 唤起）
# 陈旧清理: 目标目录中存在但源没有的 <name>.md / <name>.agent.md 会被删除
# 用法: powershell -File .agents/skills/task-pipeline/scripts/sync-agents.ps1 [-SkipZcode] [-SkipCopilot]
param(
    [switch]$SkipZcode,
    [switch]$SkipCopilot
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path
$srcDir = Join-Path $root '.agents\agents'
$copilotDir = Join-Path $root '.github\agents'
$zcodeDir = Join-Path $root '.zcode\agents'

if (-not (Test-Path $srcDir)) { Write-Error "未找到规范源目录 $srcDir"; exit 1 }

$utf8 = New-Object System.Text.UTF8Encoding($false)

function Write-IfChanged([string]$path, [string]$content) {
    if ((Test-Path $path) -and ([System.IO.File]::ReadAllText($path) -ceq $content)) {
        Write-Host "[=] 无变化 $path"; return
    }
    [System.IO.File]::WriteAllText($path, $content, $utf8)
    Write-Host "[OK] 已写入 $path"
}

$names = @()
foreach ($dir in Get-ChildItem $srcDir -Directory | Sort-Object Name) {
    $agentMd = Join-Path $dir.FullName 'agent.md'
    $configJson = Join-Path $dir.FullName 'config.json'
    if (-not (Test-Path $agentMd)) { Write-Warning "[跳过] $($dir.Name) 缺少 agent.md"; continue }
    if (-not (Test-Path $configJson)) { Write-Warning "[跳过] $($dir.Name) 缺少 config.json"; continue }

    $content = [System.IO.File]::ReadAllText($agentMd)
    if ($content -notmatch '(?s)^---\s*\r?\n(.*?)\r?\n---\s*\r?\n(.*)$') {
        Write-Warning "[跳过] $($dir.Name)/agent.md 缺少 frontmatter"; continue
    }
    $front = $Matches[1]; $body = $Matches[2].TrimStart()
    $name = if ($front -match '(?m)^name:\s*(.+?)\s*$') { $Matches[1] } else { $dir.Name }
    $desc = if ($front -match '(?m)^description:\s*(.+?)\s*$') { $Matches[1] } else { '' }
    $desc = $desc.Trim('"').Trim("'")

    $cfg = Get-Content $configJson -Raw -Encoding UTF8 | ConvertFrom-Json
    $model = $cfg.model
    $zcTools = (@($cfg.tools.zcode) -join ', ')
    $cpTools = (@($cfg.tools.copilot) -join ', ')
    $names += $name
    $nl = if ($content -match "`r`n") { "`r`n" } else { "`n" }

    $modelLine = if ([string]::IsNullOrWhiteSpace("$model")) { '' } else { "model: $model$nl" }
    $note = "<!-- AUTO-GENERATED by sync-agents.ps1 — 请编辑 .agents/agents/$name/agent.md，然后重跑本脚本 -->"

    if (-not $SkipZcode) {
        New-Item -ItemType Directory -Force -Path $zcodeDir | Out-Null
        $z = "---${nl}name: $name${nl}description: $desc${nl}$modelLine" + "tools: $zcTools${nl}---${nl}$note${nl}${nl}$body"
        Write-IfChanged (Join-Path $zcodeDir "$name.md") $z
    }
    if (-not $SkipCopilot) {
        New-Item -ItemType Directory -Force -Path $copilotDir | Out-Null
        $c = "---${nl}name: $name${nl}description: $desc${nl}tools: [$cpTools]${nl}---${nl}$note${nl}$nl$body"
        Write-IfChanged (Join-Path $copilotDir "$name.agent.md") $c
    }
}

# 陈旧清理：源已不存在于 .agents/agents/ 的映射文件
if (-not $SkipZcode -and (Test-Path $zcodeDir)) {
    foreach ($f in Get-ChildItem $zcodeDir -Filter '*.md') {
        if ($names -notcontains $f.BaseName) { Remove-Item -Force $f.FullName; Write-Host "[清理] 已删除陈旧副本 $($f.FullName)" }
    }
}
if (-not $SkipCopilot -and (Test-Path $copilotDir)) {
    foreach ($f in Get-ChildItem $copilotDir -Filter '*.agent.md') {
        $base = $f.Name -replace '\.agent\.md$', ''
        if ($names -notcontains $base) { Remove-Item -Force $f.FullName; Write-Host "[清理] 已删除陈旧映射 $($f.FullName)" }
    }
}
Write-Host '同步完成。'
